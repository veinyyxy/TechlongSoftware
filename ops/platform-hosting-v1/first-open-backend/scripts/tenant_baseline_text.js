// Python str.isspace also includes the C0 information separators and excludes BOM.
const PYTHON_WHITESPACE = String.raw`[\x09-\x0d\x1c-\x20\x85\xa0\u1680\u2000-\u200a\u2028\u2029\u202f\u205f\u3000]`;
const whitespaceCharacter = new RegExp(PYTHON_WHITESPACE);
const innerWhitespace = new RegExp(`${PYTHON_WHITESPACE}+`);
const lineBreaks = /\r\n|[\n\v\f\r\x1c-\x1e\x85\u2028\u2029]/u;
const utf8Decoder = new TextDecoder("utf-8", { fatal: true, ignoreBOM: true });

function readPythonUtf8Text(path) {
  return utf8Decoder.decode(readFileSync(path)).replace(/\r\n?/g, "\n");
}

function stripPythonWhitespace(text) {
  let start = 0;
  let end = text.length;
  while (start < end && whitespaceCharacter.test(text[start])) start++;
  while (end > start && whitespaceCharacter.test(text[end - 1])) end--;
  return text.slice(start, end);
}

function splitPythonWhitespace(text) {
  const stripped = stripPythonWhitespace(text);
  return stripped ? stripped.split(innerWhitespace) : [];
}

function splitPythonLines(text) {
  const lines = text.split(lineBreaks);
  if (lines.at(-1) === "") lines.pop();
  return lines;
}

function compareCodePoints(left, right) {
  const a = left[Symbol.iterator]();
  const b = right[Symbol.iterator]();
  while (true) {
    const x = a.next();
    const y = b.next();
    if (x.done) return y.done ? 0 : -1;
    if (y.done) return 1;
    const order = x.value.codePointAt(0) - y.value.codePointAt(0);
    if (order !== 0) return order;
  }
}

function caseFold(text) {
  return Array.from(text, character => caseFolds.get(character.codePointAt(0)) ?? character).join("");
}

